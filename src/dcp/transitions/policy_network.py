@dataclass
class PolicyFeatures:
    """Encoded features for a single track, ready for policy network."""

    duration_s: float
    tempo_bpm: Optional[float]
    tempo_confidence: float
    key: Optional[str]
    key_confidence: float
    camelot_code: Optional[str]
    downbeat_count: int
    beat_count: int
    loudness_lufs: Optional[float]
    loudness_lra: Optional[float]
    spectral_centroid_mean: Optional[float]
    spectral_bandwidth_mean: Optional[float]
    mfcc_mean: tuple[float, ...]
    genre_embedding: Optional[np.ndarray] = None


def extract_policy_features(analysis: TrackAnalysis) -> PolicyFeatures:
    """Extract and normalize features from TrackAnalysis for policy network."""
    return PolicyFeatures(
        duration_s=analysis.duration_s,
        tempo_bpm=analysis.tempo_bpm,
        tempo_confidence=analysis.tempo_confidence,
        key=analysis.key,
        key_confidence=analysis.key_confidence,
        camelot_code=analysis.camelot_code,
        downbeat_count=len(analysis.downbeat_times_s),
        beat_count=len(analysis.beat_times_s),
        loudness_lufs=analysis.loudness_lufs,
        loudness_lra=analysis.loudness_lra,
        spectral_centroid_mean=analysis.spectral_centroid_mean,
        spectral_bandwidth_mean=analysis.spectral_bandwidth_mean,
        mfcc_mean=analysis.mfcc_mean if analysis.mfcc_mean else (),
    )


def policy_features_to_tensor(features: PolicyFeatures, device: str = "cpu") -> "torch.Tensor":
    """Convert PolicyFeatures to a fixed-size tensor for the network."""
    if not _TORCH_AVAILABLE:
        raise RuntimeError("PyTorch required for neural policy network.")

    import torch

    # Normalize features to fixed-size vector
    feat_vec = []

    # Duration (normalized to 0-1, assuming max 600s)
    feat_vec.append(min(features.duration_s / 600.0, 1.0))

    # Tempo (normalized to 0-1, assuming 60-180 BPM range)
    if features.tempo_bpm is not None:
        feat_vec.append((features.tempo_bpm - 60.0) / 120.0)
    else:
        feat_vec.append(0.5)

    feat_vec.append(features.tempo_confidence)

    # Key (24 classes one-hot, simplified to confidence)
    feat_vec.append(features.key_confidence)

    # Downbeat/beat counts (normalized)
    feat_vec.append(min(features.downbeat_count / 20.0, 1.0))
    feat_vec.append(min(features.beat_count / 100.0, 1.0))

    # Loudness (normalized, assuming -30 to 0 LUFS)
    if features.loudness_lufs is not None:
        feat_vec.append((features.loudness_lufs + 30.0) / 30.0)
    else:
        feat_vec.append(0.5)

    if features.loudness_lra is not None:
        feat_vec.append(min(features.loudness_lra / 20.0, 1.0))
    else:
        feat_vec.append(0.5)

    # Timbre
    if features.spectral_centroid_mean is not None:
        feat_vec.append(min(features.spectral_centroid_mean / 8000.0, 1.0))
    else:
        feat_vec.append(0.5)

    if features.spectral_bandwidth_mean is not None:
        feat_vec.append(min(features.spectral_bandwidth_mean / 8000.0, 1.0))
    else:
        feat_vec.append(0.5)

    # MFCC (first 13 coefficients, normalized)
    for mfcc in features.mfcc_mean[:13]:
        feat_vec.append(min(max((mfcc + 20.0) / 40.0, 0.0), 1.0))

    # Pad to fixed size (64 dims)
    while len(feat_vec) < 64:
        feat_vec.append(0.0)
    feat_vec = feat_vec[:64]

    return torch.tensor(feat_vec, dtype=torch.float32, device=device).unsqueeze(0)


class NeuralPlanStrategy:
    """
    Neural policy-based transition strategy.

    Uses a trained PolicyNetwork to predict structured TransitionParams
    from track analysis features, then builds the deterministic automation
    curves using the existing curve engine.
    """

    name = "neural"
    description = "Neural policy network predicting structured transition parameters."

    def __init__(
        self,
        model_path: Optional[str] = None,
        device: str = "cpu",
        config: Optional[DCPConfig] = None,
    ):
        if not _TORCH_AVAILABLE:
            raise RuntimeError("PyTorch required for NeuralPlanStrategy. Install with: pip install torch")

        import torch

        self.device = device
        self.config = config or DEFAULT_CONFIG

        # Initialize network
        self.network = PolicyNetwork().to(device)

        # Load weights if provided
        if model_path:
            self.load_weights(model_path)

        self.network.eval()

    def load_weights(self, model_path: str) -> None:
        """Load trained weights from file."""
        import torch
        state_dict = torch.load(model_path, map_location=self.device, weights_only=True)
        self.network.load_state_dict(state_dict)

    def plan(self, context: TransitionContext) -> TransitionPlan:
        """Generate a transition plan using the neural policy network."""
        # Extract features from both tracks
        features_a = extract_policy_features(context.analysis_a)
        features_b = extract_policy_features(context.analysis_b)

        # Convert to tensors
        tensor_a = policy_features_to_tensor(features_a, self.device)
        tensor_b = policy_features_to_tensor(features_b, self.device)

        # Predict TransitionParams
        params = self.network.predict_params(tensor_a, tensor_b)

        # Build deterministic TransitionPlan from params
        # This delegates to the existing curve engine for click-free curves
        return self._build_plan_from_params(context, params)

    def _build_plan_from_params(
        self,
        context: TransitionContext,
        params: TransitionParams,
    ) -> TransitionPlan:
        """Build a deterministic TransitionPlan from neural policy parameters.

        This constructs the transition plan directly from the structured
        TransitionParams predicted by the neural network, using the
        deterministic curve engine to generate smoothstep automation curves.
        """
        from .plan import (
            TransitionPlan,
            StemAutomation,
            GainPoint,
            EffectSpec,
        )
        from .curves import interpolate_gain
        from .strategies import _views, _fade_points, _transition_times, _make_plan, _ordered_names
        from ..models import MIX_STEM

        # Get the view of stems for both tracks
        view_a, view_b, warnings, reasoning = _views(context)

        # Create automations based on the predicted parameters
        automations: list[StemAutomation] = []

        # Duration in seconds
        duration_s = float(params.duration_bars * 4 * 60.0 / context.analysis_a.tempo_bpm)
        if duration_s <= 0:
            duration_s = 8.0  # fallback

        # Get transition timing
        start_time_s, end_time_s = _transition_times(context, duration_s)

        # Get configuration
        cfg = context.config
        floor_db = cfg.transition.fade_floor_db

        # Map strategy type to window functions
        # The neural params provide structured timing for each stem
        # We'll use the predicted parameters to construct the automations

        # Get the downbeat times for timing reference
        beats_a = context.analysis_a.downbeat_times_s
        beats_b = context.analysis_b.downbeat_times_s

        # Calculate bar duration
        tempo_a = context.analysis_a.tempo_bpm or 120.0
        beat_duration = 60.0 / tempo_a
        bar_duration = beat_duration * 4

        # Build automations for each stem in view_a (Song A)
        for stem in _ordered_names(view_a):
            # Get timing parameters from params
            if stem == "vocals":
                start_frac, end_frac = params.vocal_handoff
                # For Song A, vocals fade out
                start_s = start_frac * duration_s
                end_s = end_frac * duration_s
                fade_in = False
            elif stem == "bass":
                # Bass crossover at specified bar
                crossover_time = params.bass_crossover_bar * bar_duration
                start_s = 0.0
                end_s = min(crossover_time, duration_s)
                fade_in = False
            elif stem == "drums":
                # Drums blend for specified bars
                blend_duration = params.drum_blend_bars * bar_duration
                start_s = max(0.0, duration_s - blend_duration)
                end_s = duration_s
                fade_in = False
            else:  # "other" or mix
                # Other stems enter early
                start_s = 0.0
                end_s = duration_s
                fade_in = True if stem != MIX_STEM else False

            # Clamp to transition window
            start_s = max(0.0, min(start_s, duration_s))
            end_s = max(start_s, min(end_s, duration_s))

            if stem == MIX_STEM:
                fade_in = False
                start_s = 0.0
                end_s = duration_s

            points = _fade_points(
                duration_s,
                start_s,
                end_s,
                fade_in=fade_in,
                floor_db=floor_db,
            )

            # Add filter effects if specified
            effects = ()
            filter_key = f"{'a' if False else 'b'}/{stem}"  # This is for Song A
            # Check for filter targets in params
            filter_hz = params.filter_target_hz.get(f"{stem}_lowpass")
            if filter_hz is not None and stem != MIX_STEM:
                effects = (EffectSpec(
                    kind="lowpass_sweep",
                    start_hz=16000.0,
                    end_hz=filter_hz,
                    start_s=0.0,
                    end_s=duration_s,
                ),)

            automations.append(StemAutomation(
                source="a",
                stem=stem,
                curve="smoothstep",
                points=points,
                effects=effects,
            ))

        # Build automations for each stem in view_b (Song B)
        for stem in _ordered_names(view_b):
            if stem == "vocals":
                start_frac, end_frac = params.vocal_handoff
                # For Song B, vocals fade in
                start_s = (1.0 - params.vocal_handoff[1]) * duration_s
                end_s = duration_s
                fade_in = True
            elif stem == "bass":
                # Bass enters early
                start_s = 0.0
                end_s = min(params.bass_crossover_bar * bar_duration, duration_s)
                fade_in = True
            elif stem == "drums":
                # Drums blend for specified bars
                blend_duration = params.drum_blend_bars * bar_duration
                start_s = max(0.0, duration_s - blend_duration)
                end_s = duration_s
                fade_in = True
            else:  # "other" or mix
                start_s = 0.0
                end_s = duration_s
                fade_in = True if stem != MIX_STEM else False

            if stem == MIX_STEM:
                fade_in = True
                start_s = 0.0
                end_s = duration_s

            # Clamp to transition window
            start_s = max(0.0, min(start_s, duration_s))
            end_s = max(start_s, min(end_s, duration_s))

            points = _fade_points(
                duration_s,
                start_s,
                end_s,
                fade_in=fade_in,
                floor_db=floor_db,
            )

            # Add filter effects if specified
            effects = ()
            filter_hz = params.filter_target_hz.get(f"{stem}_lowpass")
            if filter_hz is not None and stem != MIX_STEM:
                effects = (EffectSpec(
                    kind="lowpass_sweep",
                    start_hz=filter_hz,
                    end_hz=16000.0,
                    start_s=0.0,
                    end_s=duration_s,
                ),)

            automations.append(StemAutomation(
                source="b",
                stem=stem,
                curve="smoothstep",
                points=points,
                effects=effects,
            ))

        # Add metadata
        metadata = {
            "neural_policy": True,
            "predicted_params": params.to_dict(),
            "strategy": params.strategy_type,
        }

        # Build the plan
        plan = _make_plan(
            context=context,
            strategy="neural",
            duration_s=duration_s,
            automations=automations,
            reasoning=[],
            warnings=[],
            metadata=metadata,
        )

        return plan


