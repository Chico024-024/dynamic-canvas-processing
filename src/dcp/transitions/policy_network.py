    class FeatureEncoder(nn.Module):
        """Encodes TrackAnalysis features into a fixed-dimensional vector."""

        def __init__(
            self,
            input_dim: int = 64,
            hidden_dim: int = 256,
            output_dim: int = 256,
            num_layers: int = 3,
            dropout: float = 0.1,
        ):
            super().__init__()
            self.input_dim = input_dim

            layers = []
            in_dim = input_dim
            for i in range(num_layers):
                out_dim = hidden_dim if i < num_layers - 1 else output_dim
                layers.extend([
                    nn.Linear(in_dim, out_dim),
                    nn.LayerNorm(out_dim),
                    nn.ReLU(),
                    nn.Dropout(dropout),
                ])
                in_dim = out_dim

            self.encoder = nn.Sequential(*layers)

        def forward(self, x: torch.Tensor) -> torch.Tensor:
            """Encode features: [batch, input_dim] -> [batch, output_dim]"""
            return self.encoder(x)

    class CrossTrackAttention(nn.Module):
        """Cross-attention between Song A and Song B features."""

        def __init__(
            self,
            dim: int = 256,
            num_heads: int = 8,
            dropout: float = 0.1,
        ):
            super().__init__()
            self.dim = dim
            self.num_heads = num_heads
            self.head_dim = dim // num_heads

            self.q_proj = nn.Linear(dim, dim)
            self.k_proj = nn.Linear(dim, dim)
            self.v_proj = nn.Linear(dim, dim)
            self.out_proj = nn.Linear(dim, dim)
            self.dropout = nn.Dropout(dropout)
            self.scale = self.head_dim ** -0.5

        def forward(
            self,
            x_a: torch.Tensor,  # [batch, seq_len_a, dim]
            x_b: torch.Tensor,  # [batch, seq_len_b, dim]
        ) -> torch.Tensor:
            """Cross-attention: A attends to B, B attends to A."""
            batch, seq_a, _ = x_a.shape
            _, seq_b, _ = x_b.shape

            # Project
            q_a = self.q_proj(x_a).view(batch, seq_a, self.num_heads, self.head_dim).transpose(1, 2)
            k_a = self.k_proj(x_a).view(batch, seq_a, self.num_heads, self.head_dim).transpose(1, 2)
            v_a = self.v_proj(x_a).view(batch, seq_a, self.num_heads, self.head_dim).transpose(1, 2)

            q_b = self.q_proj(x_b).view(batch, seq_b, self.num_heads, self.head_dim).transpose(1, 2)
            k_b = self.k_proj(x_b).view(batch, seq_b, self.num_heads, self.head_dim).transpose(1, 2)
            v_b = self.v_proj(x_b).view(batch, seq_b, self.num_heads, self.head_dim).transpose(1, 2)

            # A attends to B
            attn_ab = torch.matmul(q_a, k_b.transpose(-2, -1)) * self.scale
            attn_ab = F.softmax(attn_ab, dim=-1)
            attn_ab = self.dropout(attn_ab)
            out_a = torch.matmul(attn_ab, v_b).transpose(1, 2).contiguous().view(batch, seq_a, -1)

            # B attends to A
            attn_ba = torch.matmul(q_b, k_a.transpose(-2, -1)) * self.scale
            attn_ba = F.softmax(attn_ba, dim=-1)
            attn_ba = self.dropout(attn_ba)
            out_b = torch.matmul(attn_ba, v_a).transpose(1, 2).contiguous().view(batch, seq_b, -1)

            # Combine
            out = torch.cat([out_a, out_b], dim=1)  # [batch, seq_a+seq_b, dim]
            return self.out_proj(out)

    class PolicyNetwork(nn.Module):
        """
        Transformer-based policy network for transition parameter prediction.

        Takes encoded features from both tracks and predicts structured
        TransitionParams.
        """

        def __init__(
            self,
            feature_dim: int = 64,
            hidden_dim: int = 256,
            num_heads: int = 8,
            num_layers: int = 4,
            dropout: float = 0.1,
            max_bars: int = 16,
        ):
            super().__init__()
            self.max_bars = max_bars

            # Feature encoders for each track
            self.encoder_a = FeatureEncoder(feature_dim, hidden_dim, hidden_dim)
            self.encoder_b = FeatureEncoder(feature_dim, hidden_dim, hidden_dim)

            # Cross-track attention
            self.cross_attention = CrossTrackAttention(hidden_dim, num_heads, dropout)

            # Transformer encoder for combined sequence
            encoder_layer = nn.TransformerEncoderLayer(
                d_model=hidden_dim,
                nhead=num_heads,
                dim_feedforward=hidden_dim * 4,
                dropout=dropout,
                batch_first=True,
                activation="gelu",
            )
            self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)

            # Output heads for each TransitionParams field
            self.strategy_head = nn.Linear(hidden_dim, 6)  # 6 strategy types
            self.duration_bars_head = nn.Linear(hidden_dim, max_bars)
            self.anchor_bar_a_head = nn.Linear(hidden_dim, max_bars)
            self.anchor_bar_b_head = nn.Linear(hidden_dim, max_bars)
            self.vocal_handoff_out_head = nn.Linear(hidden_dim, 20)  # 0-20s range
            self.vocal_handoff_in_head = nn.Linear(hidden_dim, 20)
            self.bass_crossover_head = nn.Linear(hidden_dim, max_bars)
            self.drum_blend_head = nn.Linear(hidden_dim, max_bars)
            self.cue_offset_head = nn.Linear(hidden_dim, 1)  # Continuous

            # Filter target prediction (per stem)
            self.filter_target_head = nn.Linear(hidden_dim, 4 * 10)  # 4 stems * 10 freq bins

        def forward(
            self,
            features_a: torch.Tensor,  # [batch, feature_dim]
            features_b: torch.Tensor,  # [batch, feature_dim]
        ) -> dict[str, torch.Tensor]:
            """Forward pass returning logits for each TransitionParams field."""
            batch = features_a.shape[0]

            # Encode each track
            enc_a = self.encoder_a(features_a).unsqueeze(1)  # [batch, 1, hidden]
            enc_b = self.encoder_b(features_b).unsqueeze(1)  # [batch, 1, hidden]

            # Cross-attention
            cross_out = self.cross_attention(enc_a, enc_b)  # [batch, 2, hidden*2]

            # Transformer
            trans_out = self.transformer(cross_out)  # [batch, 2, hidden*2]
            pooled = trans_out.mean(dim=1)  # [batch, hidden*2]

            # Output heads
            return {
                "strategy_type": self.strategy_head(pooled),
                "duration_bars": self.duration_bars_head(pooled),
                "anchor_bar_a": self.anchor_bar_a_head(pooled),
                "anchor_bar_b": self.anchor_bar_b_head(pooled),
                "vocal_handoff_out": self.vocal_handoff_out_head(pooled),
                "vocal_handoff_in": self.vocal_handoff_in_head(pooled),
                "bass_crossover_bar": self.bass_crossover_head(pooled),
                "drum_blend_bars": self.drum_blend_head(pooled),
                "cue_offset": self.cue_offset_head(pooled).squeeze(-1),
                "filter_targets": self.filter_target_head(pooled).view(batch, 4, 10),
            }

        def predict_params(
            self,
            features_a: torch.Tensor,
            features_b: torch.Tensor,
        ) -> TransitionParams:
            """Predict TransitionParams from features (inference mode)."""
            self.eval()
            with torch.no_grad():
                logits = self.forward(features_a, features_b)

                # Apply softmax and get predictions
                strategy_idx = logits["strategy_type"].argmax(-1).item()
                strategy_types = ["stem_level", "rhythmic", "atmospheric", "conservative", "crossfade", "neural"]
                strategy_type = strategy_types[strategy_idx]

                duration_bars = logits["duration_bars"].argmax(-1).item() + 1
                anchor_bar_a = logits["anchor_bar_a"].argmax(-1).item() + 1
                anchor_bar_b = logits["anchor_bar_b"].argmax(-1).item() + 1

                # Vocal handoff (continuous, scaled to 0-20s)
                vocal_out = torch.sigmoid(logits["vocal_handoff_out"]).argmax(-1).item() * 20.0 / 19
                vocal_in = torch.sigmoid(logits["vocal_handoff_in"]).argmax(-1).item() * 20.0 / 19

                bass_crossover = logits["bass_crossover_bar"].argmax(-1).item() + 1
                drum_blend = logits["drum_blend_bars"].argmax(-1).item() + 1
                cue_offset = torch.sigmoid(logits["cue_offset"]).item() * 4.0  # 0-4s range

                # Filter targets (simplified)
                filter_targets = torch.sigmoid(logits["filter_targets"])
                stems = ["vocals", "bass", "drums", "other"]
                freq_bins = np.linspace(100, 16000, 10)
                filter_dict = {}
                for i, stem in enumerate(stems):
                    # Pick peak frequency bin
                    peak_bin = filter_targets[0, i].argmax().item()
                    filter_dict[f"{stem}_lowpass"] = float(freq_bins[peak_bin])

                return TransitionParams(
                    strategy_type=strategy_type,
                    duration_bars=duration_bars,
                    anchor_bar_a=anchor_bar_a,
                    anchor_bar_b=anchor_bar_b,
                    vocal_handoff=(vocal_out, vocal_in),
                    bass_crossover_bar=bass_crossover,
                    drum_blend_bars=drum_blend,
                    cue_offset_b_s=cue_offset,
                    filter_target_hz=filter_dict,
                )

